// Generates the outer pnpm workspace from t3code's (ADR-0001): pnpm reads the catalog,
// overrides, patchedDependencies and the lockfile only at the workspace root, so we derive
// them from the submodule instead of copying them by hand.
//
//   node scripts/gen-workspace.ts          # writes pnpm-workspace.yaml and seeds pnpm-lock.yaml
//
// The transform is line-based so t3's comments survive and no YAML dependency is needed
// before the first install.
import * as fs from "node:fs";
import * as path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const t3 = path.join(root, "t3code");
const PREFIX = "t3code/";

// The t3 workspace packages we build against: the server, the web client and their
// workspace dependencies. Desktop, mobile, marketing, evals and infra are left out.
const T3_PACKAGES = ["apps/server", "apps/web", "packages/*"];
const OUR_PACKAGES = ["apps/*", "packages/*"];

const src = fs.readFileSync(path.join(t3, "pnpm-workspace.yaml"), "utf8").split("\n");
const out: string[] = [
  "# GENERATED by scripts/gen-workspace.ts from t3code/pnpm-workspace.yaml. Do not edit.",
  "packages:",
  ...OUR_PACKAGES.map((p) => `  - ${p}`),
  ...T3_PACKAGES.map((p) => `  - ${PREFIX}${p}`),
  "",
  "# Patches whose package only desktop or mobile installs are unused here.",
  "allowUnusedPatches: true",
  "",
];

let section = "";
let skip = false;
for (const line of src) {
  const top = /^([A-Za-z][\w-]*):/.exec(line);
  if (top) {
    section = top[1]!;
    skip = section === "packages";
    if (skip) continue;
  }
  if (skip) continue;
  let l = line;
  if (section === "patchedDependencies") l = l.replace(/: patches\//, `: ${PREFIX}patches/`);
  // file: specs are relative to the t3 root.
  l = l.replace(/file:(apps|packages)\//g, `file:${PREFIX}$1/`);
  out.push(l);
}
fs.writeFileSync(path.join(root, "pnpm-workspace.yaml"), out.join("\n"));

// Seed our lockfile from t3's so the server and web resolve to exactly what t3 tested.
// Importer keys get the submodule prefix; importers we do not install are dropped and
// pnpm resolves our own on the next install.
const lockPath = path.join(root, "pnpm-lock.yaml");
if (!fs.existsSync(lockPath) || process.argv.includes("--reseed-lock")) {
  const keep = (key: string) =>
    T3_PACKAGES.some((p) =>
      p.endsWith("/*") ? key.startsWith(p.slice(0, -1)) && !key.slice(p.length - 1).includes("/") : key === p,
    );
  const lock = fs.readFileSync(path.join(t3, "pnpm-lock.yaml"), "utf8").split("\n");
  const res: string[] = [];
  let inImporters = false;
  let dropping = false;
  let doc = 0;
  for (const line of lock) {
    if (line === "---") doc++;
    if (/^[a-zA-Z]/.test(line)) {
      // The first document is pnpm's own env lockfile; only the second lists the workspace.
      inImporters = line === "importers:" && doc >= 2;
      dropping = false;
    }
    if (inImporters) {
      const imp = /^  (\S+):$/.exec(line);
      if (imp) {
        const key = imp[1]!.replace(/^'|'$/g, "");
        dropping = key === "." || !keep(key);
        if (!dropping) {
          res.push(`  ${PREFIX}${key}:`);
          continue;
        }
      }
      if (dropping) continue;
    }
    res.push(line);
  }
  fs.writeFileSync(lockPath, res.join("\n"));
}
console.log("wrote pnpm-workspace.yaml");
