// @effect-diagnostics globalDate:off globalConsole:off globalFetch:off nodeBuiltinImport:off globalTimers:off
// SPI-1173's evidence on its stage: t3's Usage page from t3flare's own usage records.
//
//   node scripts/stage.ts deploy p1173
//   node scripts/stage.ts run p1173 p1173 [--out ../../docs/steps/spi-1173/p1173.json]
//
// 1. Three Model endpoints saved through the Harness panel's API, all Commissary's with the proxy key (SPI-1162's
//    approach): `comm` (Anthropic Messages), `oai` (Chat Completions) and `resp` (OpenAI Responses), each with one model.
//    Text generation is pointed at `comm`'s model. `comm` also lists a model pi-ai's catalog does not price
//    (`UNPRICED`), which t3's rate table does.
// 2. A turn on each agent: the Durable agent on `comm` (and its thread's title regenerated by text generation), the
//    Durable agent on the unpriced model, Codex on `resp`, Claude Code on `comm` (model-routed), pi on `oai`, OpenCode
//    on `oai`.
// 3. t3's usage summary (`server.getUsageSummary`, what the Usage page reads): a bucket per agent and model, from our
//    sources (`t3flare://usage/<agent>`), each with tokens and its cost: the endpoint's price, or t3's rate table's for
//    the unpriced model. Nothing from Commissary's request log.
//
// No key or handle is printed or kept: every answer kept is scanned for the keys first.
import { spawnSync } from "node:child_process";
import * as fs from "node:fs";

import { cliTurn as acpTurn, enable as enableAcp } from "./lib/acpTurn.ts";
import { admin, createProjectAndThread, dispatch, pair, projectionOf, runsOf, sendMessage, SETTLED, sleep, threadWindow, updateSettings, uuid, wsCall } from "./lib/client.ts";
import { cliTurn, enable } from "./lib/cliTurn.ts";

const option = (name: string) => {
  const index = process.argv.indexOf(`--${name}`);
  return index === -1 ? undefined : process.argv[index + 1];
};
const out = option("out");
const proxyUrl = (process.env.MODEL_PROXY_URL ?? "").replace(/\/+$/, "");
const proxyKey = process.env.MODEL_PROXY_API_KEY ?? "";
const secrets = [proxyKey].filter((value) => value.length >= 8);
const failures: Array<string> = [];
const head = spawnSync("git", ["rev-parse", "HEAD"], { encoding: "utf8" }).stdout.trim();
const report: Record<string, unknown> = { at: new Date().toISOString(), head };
const check = (name: string, ok: boolean, detail?: unknown) => {
  report.checks = [...((report.checks as Array<unknown>) ?? []), { name, ok }];
  if (!ok) failures.push(`${name}: ${JSON.stringify(detail ?? null).slice(0, 800)}`);
  return ok;
};
const clean = <T>(value: T): T => {
  const text = JSON.stringify(value) ?? "";
  for (const secret of secrets) if (text.includes(secret)) throw new Error("a key reached an answer kept as evidence");
  return value;
};
const finish = (): never => {
  report.failures = failures;
  report.ok = failures.length === 0;
  const text = JSON.stringify(clean(report), null, 2);
  console.log(text.slice(0, 30_000));
  if (out !== undefined) fs.writeFileSync(out, `${text}\n`);
  process.exit(report.ok ? 0 : 1);
};
const api = (method: string, pathname: string, body?: unknown) => admin(method, `/_t3flare/harness/api/${pathname}`, body);

if (proxyUrl === "" || proxyKey === "") {
  failures.push("the stage needs MODEL_PROXY_URL and MODEL_PROXY_API_KEY (dev.env)");
  finish();
}

const cookie = await pair();
await admin("POST", "/_t3flare/disarm-bootstrap");

// 1. The endpoints, and text generation on comm's model.
const MODEL = "claude-haiku-5-5";
/** A model Commissary serves that pi-ai's catalog does not know (so the endpoint has no price for it), and LiteLLM does. */
const UNPRICED = "claude-fable-5-2";
const ENDPOINTS = {
  comm: { label: "Commissary (Anthropic)", api: "anthropic-messages", baseUrl: proxyUrl },
  oai: { label: "Commissary (Chat Completions)", api: "openai-completions", baseUrl: `${proxyUrl}/v1` },
  resp: { label: "Commissary (Responses)", api: "openai-responses", baseUrl: `${proxyUrl}/v1` },
} as const;
const saved: Record<string, number> = {};
for (const [id, spec] of Object.entries(ENDPOINTS)) {
  saved[id] = (await api("POST", "endpoints", { op: "save", endpoint: { id, ...spec, auth: "api-key", headers: {}, models: id === "comm" ? [MODEL, UNPRICED] : [MODEL] }, apiKey: proxyKey })).status;
}
const listed = ((await api("GET", "endpoints")).json?.endpoints ?? []) as Array<any>;
const unpricedCost = listed.find((endpoint) => endpoint.id === "comm")?.models?.find((model: any) => model.id === UNPRICED)?.cost ?? null;
report.endpoints = { saved, model: MODEL, unpriced: { model: UNPRICED, endpointCost: unpricedCost }, baseUrls: { comm: "<MODEL_PROXY_URL>", oai: "<MODEL_PROXY_URL>/v1", resp: "<MODEL_PROXY_URL>/v1" } };
check("the three endpoints saved", Object.values(saved).every((status) => status === 200), saved);
check("the endpoint has no price for the unpriced model", unpricedCost === null || Object.values(unpricedCost).every((value) => value === 0), unpricedCost);
const SLUG = { comm: `comm/${MODEL}`, oai: `oai/${MODEL}`, resp: `resp/${MODEL}`, unpriced: `comm/${UNPRICED}` };
await wsCall(cookie, "server.updateSettings", { patch: {}, providerInstanceMutation: { operation: "upsert", instanceId: "piDurable", instance: { driver: "piDurable", enabled: true } } });
await updateSettings(cookie, { textGenerationModelSelection: { instanceId: "piDurable", model: SLUG.comm } });

// 2. A turn on each agent.
const run = Date.now().toString(36);
const turns: Record<string, unknown> = {};
const settled = (status: string | undefined) => status === "completed";

// The Durable agent: a turn on comm's model, the thread's title regenerated by text generation, then a turn on the
// unpriced model.
{
  const { threadId } = await createProjectAndThread(cookie, { title: "New thread", workspaceRoot: `/w/p1173-durable-${run}` });
  const durableTurn = async (slug: string, count: number) => {
    await sendMessage(cookie, threadId, "In one short sentence, what is a usage record?", { instanceId: "piDurable", model: slug, options: [] });
    const started = Date.now();
    let projection: any;
    while (Date.now() - started < 5 * 60_000) {
      projection = projectionOf(await threadWindow(cookie, threadId));
      const runs = runsOf(projection);
      if (runs.length >= count && runs.every((entry) => SETTLED.has(entry.status))) break;
      await sleep(1500);
    }
    return runsOf(projection).map((entry) => entry.status);
  };
  const first = await durableTurn(SLUG.comm, 1);
  check("a Durable turn on the Anthropic Messages endpoint", settled(first.at(-1)), first);
  const commandId = uuid();
  await dispatch(cookie, { type: "thread.metadata.update", commandId, threadId, regenerateTitle: true });
  let title: any = null;
  for (let i = 0; i < 60 && title?.requestId !== commandId; i++) {
    await sleep(2000);
    const projection = projectionOf(await threadWindow(cookie, threadId));
    title = projection?.thread?.lastTitleRegeneration ?? null;
  }
  check("the thread's title regenerated by text generation on the endpoint", title?.requestId === commandId && (title?.status === "renamed" || title?.status === "unchanged"), title);
  const second = await durableTurn(SLUG.unpriced, 2);
  check("a Durable turn on the unpriced model", settled(second.at(-1)), second);
  turns.durable = { threadId, runs: second, title: clean(title) };
}
const ask = "Reply with the single word: ready.";
const codex = await cliTurn(cookie, { cli: "codex", workspace: `usage-cli-${run}`, model: SLUG.resp, mode: "full-access", plan: false, prompt: ask });
turns.codex = clean({ runs: codex.runs.slice(-1), text: codex.text });
check("a Codex turn on the Responses endpoint, through the relay", settled(codex.runs.at(-1)?.status), turns.codex);
await enable(cookie, "pi", "pi");
await sleep(2000);
const pi = await cliTurn(cookie, { cli: "pi", workspace: `usage-cli-${run}`, model: SLUG.oai, mode: "full-access", plan: false, prompt: ask });
turns.pi = clean({ runs: pi.runs.slice(-1), text: pi.text });
check("a pi turn on the Chat Completions endpoint, through the relay", settled(pi.runs.at(-1)?.status), turns.pi);
await enableAcp(cookie, "claude");
await sleep(2000);
const claude = await acpTurn(cookie, { cli: "claude", workspace: `usage-acp-${run}`, model: SLUG.comm, mode: "full-access", plan: false, prompt: ask });
turns.claude = clean({ runs: claude.runs.slice(-1), text: claude.text });
check("a Claude Code turn on the Anthropic Messages endpoint, model-routed through the relay", settled(claude.runs.at(-1)?.status), turns.claude);
await enableAcp(cookie, "opencode");
await sleep(2000);
const opencode = await acpTurn(cookie, { cli: "opencode", workspace: `usage-acp-${run}`, model: SLUG.oai, mode: "full-access", plan: false, prompt: ask });
turns.opencode = clean({ runs: opencode.runs.slice(-1), text: opencode.text });
check("an OpenCode turn on the Chat Completions endpoint, through the relay", settled(opencode.runs.at(-1)?.status), turns.opencode);
report.turns = turns;

// 3. The usage summary the Usage page reads, after the records' sends have landed.
await sleep(5000);
const today = new Date().toISOString().slice(0, 10);
const yesterday = new Date(Date.now() - 86_400_000).toISOString().slice(0, 10);
const summary = (await wsCall(cookie, "server.getUsageSummary", { sinceDay: yesterday, untilDay: today, timeZone: "UTC", awaitRefresh: true })) as any;
const ours = (summary?.buckets ?? []).filter((bucket: any) => String(bucket.sourcePath ?? "").startsWith("t3flare://usage/"));
const rows = new Map<string, { provider: string; source: string; model: string; tokens: number; records: number; costUsd: number; costSource: string; sessions: number }>();
for (const bucket of ours) {
  const key = `${bucket.provider} ${bucket.sourcePath} ${bucket.model}`;
  const totals = bucket.totals ?? {};
  const row = rows.get(key) ?? { provider: bucket.provider, source: bucket.sourcePath, model: bucket.model, tokens: 0, records: 0, costUsd: 0, costSource: bucket.costSource, sessions: 0 };
  row.tokens += (totals.uncachedInputTokens ?? 0) + (totals.cachedInputTokens ?? 0) + (totals.cacheCreationTokens ?? 0) + (totals.outputTokens ?? 0);
  row.records += bucket.records ?? 0;
  row.costUsd += bucket.costUsd ?? 0;
  row.sessions = Math.max(row.sessions, bucket.sessions ?? 0);
  rows.set(key, row);
}
const table = [...rows.values()].sort((a, b) => `${a.provider}${a.source}`.localeCompare(`${b.provider}${b.source}`));
report.usage = clean({
  table,
  sources: (summary?.sources ?? []).filter((source: any) => String(source.fingerprint?.resolvedHomePath ?? "").startsWith("t3flare://")).map((source: any) => ({ provider: source.fingerprint.provider, source: source.fingerprint.resolvedHomePath, status: source.status, scannedFiles: source.scannedFiles, distinctSessions: source.distinctSessions, message: source.message })),
  pricing: summary?.pricing,
});
const has = (provider: string, source: string, model: string) => table.some((row) => row.provider === provider && row.source === `t3flare://usage/${source}` && row.model === model && row.tokens > 0);
check("the Usage page counts the Durable agent's turn under Pi, by its endpoint's model", has("pi", "durable", SLUG.comm), table);
check("and text generation's title, under Pi", has("pi", "text-generation", SLUG.comm), table);
check("Codex's turn under Codex, by the Responses endpoint's model", has("codex", "codex", SLUG.resp), table);
check("Claude Code's turn under Claude, by the Anthropic endpoint's model", has("claude", "claude", SLUG.comm), table);
check("pi's turn under Pi (the pi CLI's source), by the Chat Completions endpoint's model", has("pi", "pi", SLUG.oai), table);
check("OpenCode's turn under OpenCode, by the Chat Completions endpoint's model", has("opencode", "opencode", SLUG.oai), table);
check("the endpoints' priced model's rows carry the cost the Session or the Environment priced", table.filter((row) => row.model.endsWith(`/${MODEL}`)).every((row) => row.costSource === "providerReported" && row.costUsd > 0), table);
check("the unpriced model's row is priced by t3's rate table", table.some((row) => row.model === SLUG.unpriced && row.costSource === "modelPriced" && row.costUsd > 0), table);
check("nothing on the page from Commissary's request log", !(summary?.buckets ?? []).some((bucket: any) => String(bucket.sourcePath ?? "").startsWith("commissary://")) && !(summary?.sources ?? []).some((source: any) => String(source.fingerprint?.resolvedHomePath ?? "").startsWith("commissary://")), summary?.sources);
finish();
